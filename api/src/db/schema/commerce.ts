/**
 * Contact-form messages.
 *
 * This is the table `0001_enquiries_and_trip_requests.sql` describes, carried
 * over field for field so the existing server actions keep working. Two
 * columns are added: `user_id`, for when a signed-in person writes in, and
 * `assigned_to_user_id`, because an office of more than one needs to know
 * whose reply is outstanding.
 */
export const enquiries = pgTable(
  "enquiries",
  {
    id: uuid("id").defaultRandom().primaryKey(),
    createdAt: timestamp("created_at", { withTimezone: true })
      .notNull()
      .defaultNow(),

    userId: uuid("user_id").references(() => users.id, {
      onDelete: "set null",
    }),

    name: text("name").notNull(),
    email: text("email").notNull(),
    phone: text("phone"),

    /*
     * A destination slug, but kept as the enum rather than a foreign key to
     * `destinations`: the form offers the eight states whether or not a
     * destination row has been published yet, and an unpublished draft must
     * not make the contact form reject a lead.
     */
    state: stateSlug("state"),
    month: text("month"),
    partySize: integer("party_size"),

    message: text("message").notNull(),

    /** Which form it came from. 'contact', 'expedition-booking', … */
    source: text("source").notNull().default("contact"),

    status: enquiryStatus("status").notNull().default("new"),
    assignedToUserId: uuid("assigned_to_user_id").references(() => users.id, {
      onDelete: "set null",
    }),
    staffNotes: text("staff_notes"),
    handledAt: timestamp("handled_at", { withTimezone: true }),
  },
  (t) => [
    index("enquiries_created_at_idx").on(t.createdAt),
    index("enquiries_status_idx").on(t.status, t.createdAt),
    index("enquiries_email_idx").on(t.email),
    check(
      "enquiries_party_size_positive",
      sql`${t.partySize} is null or ${t.partySize} > 0`,
    ),
  ],
);

/**
 * A completed run through the planner.
 *
 * `plan` holds the whole quote as it was shown. The itinerary is composed
 * from content the client can now edit, which makes the snapshot more
 * important than it was when that content was code: a supplement changed in
 * March must not rewrite what somebody was quoted in November.
 */
export const tripRequests = pgTable(
  "trip_requests",
  {
    id: uuid("id").defaultRandom().primaryKey(),
    createdAt: timestamp("created_at", { withTimezone: true })
      .notNull()
      .defaultNow(),

    reference: text("reference").notNull().unique(),
    userId: uuid("user_id").references(() => users.id, {
      onDelete: "set null",
    }),

    state: stateSlug("state").notNull(),
    stateName: text("state_name").notNull(),
    party: text("party").notNull(),

    startDate: date("start_date").notNull(),
    endDate: date("end_date").notNull(),
    nights: integer("nights").notNull(),
    adults: integer("adults").notNull(),
    children: integer("children").notNull().default(0),
    childAges: jsonb("child_ages")
      .notNull()
      .default(sql`'[]'::jsonb`),

    leadName: text("lead_name").notNull(),
    leadEmail: text("lead_email").notNull(),
    leadPhone: text("lead_phone").notNull(),
    companions: jsonb("companions")
      .notNull()
      .default(sql`'[]'::jsonb`),
    travellerNotes: text("traveller_notes"),

    /** What they chose, day by day: rooms, transfers, vehicle, activities. */
    selections: jsonb("selections")
      .notNull()
      .default(sql`'{}'::jsonb`),
    /** The quote as quoted. */
    plan: jsonb("plan").notNull(),

    total: integer("total").notNull(),
    deposit: integer("deposit").notNull().default(0),

    status: tripRequestStatus("status").notNull().default("new"),
    assignedToUserId: uuid("assigned_to_user_id").references(() => users.id, {
      onDelete: "set null",
    }),
    staffNotes: text("staff_notes"),
    handledAt: timestamp("handled_at", { withTimezone: true }),

    /** Set when the office turned this into a real booking. */
    bookingId: uuid("booking_id").references(() => bookings.id, {
      onDelete: "set null",
    }),
  },
  (t) => [
    index("trip_requests_created_at_idx").on(t.createdAt),
    index("trip_requests_status_idx").on(t.status, t.createdAt),
    index("trip_requests_start_date_idx").on(t.startDate),
    check("trip_requests_nights_positive", sql`${t.nights} > 0`),
    check("trip_requests_adults_positive", sql`${t.adults} > 0`),
    check("trip_requests_children_nonneg", sql`${t.children} >= 0`),
    check("trip_requests_total_nonneg", sql`${t.total} >= 0`),
    check("trip_requests_dates_ordered", sql`${t.endDate} >= ${t.startDate}`),
  ],
);
