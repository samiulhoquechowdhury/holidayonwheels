import { sql } from "drizzle-orm";
import {
  stateSlug,
  bookingKind,
  bookingStatus,
  permitKind,
  permitStatus,
  enquiryStatus,
  tripRequestStatus,
} from "./enums";
import { users } from "./auth";
import {
  tours,
  motorcycleTours,
  homestays,
  events,
  departures,
} from "./content";

/**
 * What the business sells and what people send it.
 *
 * ## Why a booking stores a title and a price as well as a product id
 *
 * `bookings.title` and `bookings.total` duplicate what could be joined from
 * `tours`. That duplication is the point. A booking is a record of an
 * agreement: it must keep saying what was sold and for how much after the
 * client raises the price next March or renames the trip. The foreign key is
 * there so the office can still get to the product; the snapshot is there so
 * the traveller's confirmation never silently changes.
 *
 * This is the same reasoning as `trip_requests.plan`, which the first
 * migration already stated, applied consistently.
 *
 * ## Why `user_id` is nullable everywhere
 *
 * The site takes enquiries and bookings from people who are not signed in,
 * and that has to keep working — forcing an account before a phone number is
 * how a travel business loses leads. Where an account exists the row is
 * linked; where it does not, the email is the only identity, and a later
 * sign-up can claim the row by matching it.
 */

/* ======================================================================= */
/* Bookings                                                               */
/* ======================================================================= */

export const bookings = pgTable(
  "bookings",
  {
    id: uuid("id").defaultRandom().primaryKey(),

    /**
     * The string a traveller reads out on the phone — "HOW-4K7M2Q". Unique,
     * and generated by the application rather than the database because the
     * office already uses this format and a sequence would produce guessable
     * neighbours.
     */
    reference: text("reference").notNull().unique(),

    userId: uuid("user_id").references(() => users.id, {
      onDelete: "set null",
    }),

    kind: bookingKind("kind").notNull(),

    /*
     * One nullable FK per catalogue, and a CHECK that the one matching `kind`
     * is the one that is set. The alternative, a bare `item_slug`, is what
     * the old content files used and it cannot be enforced at all: a typo'd
     * slug becomes a booking for a product that does not exist.
     */
    tourId: uuid("tour_id").references(() => tours.id, {
      onDelete: "restrict",
    }),
    motorcycleTourId: uuid("motorcycle_tour_id").references(
      () => motorcycleTours.id,
      { onDelete: "restrict" },
    ),
    homestayId: uuid("homestay_id").references(() => homestays.id, {
      onDelete: "restrict",
    }),
    eventId: uuid("event_id").references(() => events.id, {
      onDelete: "restrict",
    }),

    /** Which departure, where the product has them. */
    departureId: uuid("departure_id").references(() => departures.id, {
      onDelete: "set null",
    }),

    /* --- The snapshot. See the note above. ------------------------------ */
    title: text("title").notNull(),
    itemSlug: text("item_slug").notNull(),
    region: text("region").notNull(),

    startDate: date("start_date").notNull(),
    endDate: date("end_date").notNull(),
    travellers: integer("travellers").notNull(),
    /** Whole rupees, as quoted. */
    total: integer("total").notNull(),
    deposit: integer("deposit").notNull().default(0),
    /** What has actually been received. */
    amountPaid: integer("amount_paid").notNull().default(0),

    /* --- Who is travelling --------------------------------------------- */
    leadName: text("lead_name").notNull(),
    leadEmail: text("lead_email").notNull(),
    leadPhone: text("lead_phone").notNull(),
    /** `{ name, age? }[]` — read whole, never queried into. */
    companions: jsonb("companions")
      .notNull()
      .default(sql`'[]'::jsonb`),
    travellerNotes: text("traveller_notes"),

    status: bookingStatus("status").notNull().default("pending-payment"),
    /** Never shown to the traveller. */
    staffNotes: text("staff_notes"),

    bookedAt: timestamp("booked_at", { withTimezone: true })
      .notNull()
      .defaultNow(),
    cancelledAt: timestamp("cancelled_at", { withTimezone: true }),
    createdAt: timestamp("created_at", { withTimezone: true })
      .notNull()
      .defaultNow(),
    updatedAt: timestamp("updated_at", { withTimezone: true })
      .notNull()
      .defaultNow(),
  },
  (t) => [
    index("bookings_user_idx").on(t.userId, t.bookedAt),
    index("bookings_status_idx").on(t.status, t.bookedAt),
    index("bookings_start_date_idx").on(t.startDate),
    index("bookings_lead_email_idx").on(t.leadEmail),
    check("bookings_travellers_positive", sql`${t.travellers} > 0`),
    check("bookings_total_nonneg", sql`${t.total} >= 0`),
    check(
      "bookings_paid_within_total",
      sql`${t.amountPaid} >= 0 and ${t.amountPaid} <= ${t.total}`,
    ),
    check("bookings_dates_ordered", sql`${t.endDate} >= ${t.startDate}`),
    /*
     * The product referenced must be the kind the booking says it is. Without
     * this, a 'tour' booking could carry only an `event_id` and every join
     * that trusts `kind` would silently return nothing.
     */
    check(
      "bookings_product_matches_kind",
      sql`case ${t.kind}
            when 'tour'  then ${t.tourId} is not null
            when 'moto'  then ${t.motorcycleTourId} is not null
            when 'stay'  then ${t.homestayId} is not null
            when 'event' then ${t.eventId} is not null
          end`,
    ),
  ],
);

/**
 * Money received against a booking.
 *
 * A separate table and not a column, because a trip is paid in a deposit and
 * a balance, sometimes refunded in part, and `bookings.amount_paid` alone
 * cannot say when or how. That column stays as the running total the admin
 * lists by; this is the ledger behind it.
 */
export const payments = pgTable(
  "payments",
  {
    id: uuid("id").defaultRandom().primaryKey(),
    bookingId: uuid("booking_id")
      .notNull()
      .references(() => bookings.id, { onDelete: "cascade" }),

    /** Negative for a refund, which is why there is no `kind` column. */
    amount: integer("amount").notNull(),
    /** "bank-transfer", "upi", "card", "cash". Free text: it will grow. */
    method: text("method").notNull(),
    /** The gateway's or the bank's own reference, for reconciliation. */
    externalReference: text("external_reference"),
    note: text("note"),

    /** The staff member who recorded it. */
    recordedByUserId: uuid("recorded_by_user_id").references(() => users.id, {
      onDelete: "set null",
    }),
    receivedAt: timestamp("received_at", { withTimezone: true })
      .notNull()
      .defaultNow(),
    createdAt: timestamp("created_at", { withTimezone: true })
      .notNull()
      .defaultNow(),
  },
  (t) => [
    index("payments_booking_idx").on(t.bookingId, t.receivedAt),
    check("payments_amount_nonzero", sql`${t.amount} <> 0`),
  ],
);

/* ======================================================================= */
/* Permits                                                                */
/* ======================================================================= */

export const permits = pgTable(
  "permits",
  {
    id: uuid("id").defaultRandom().primaryKey(),
    reference: text("reference").notNull().unique(),

    userId: uuid("user_id").references(() => users.id, {
      onDelete: "set null",
    }),
    bookingId: uuid("booking_id").references(() => bookings.id, {
      onDelete: "set null",
    }),

    state: stateSlug("state").notNull(),
    kind: permitKind("kind").notNull(),
    travellerName: text("traveller_name").notNull(),

    validFrom: date("valid_from").notNull(),
    validTo: date("valid_to").notNull(),

    status: permitStatus("status").notNull().default("draft"),
    submittedAt: timestamp("submitted_at", { withTimezone: true }),
    decidedAt: timestamp("decided_at", { withTimezone: true }),
    /** Why it was refused, in the issuing authority's words. */
    rejectionReason: text("rejection_reason"),
    staffNotes: text("staff_notes"),

    createdAt: timestamp("created_at", { withTimezone: true })
      .notNull()
      .defaultNow(),
    updatedAt: timestamp("updated_at", { withTimezone: true })
      .notNull()
      .defaultNow(),
  },
  (t) => [
    index("permits_user_idx").on(t.userId),
    index("permits_status_idx").on(t.status, t.validFrom),
    index("permits_booking_idx").on(t.bookingId),
    check("permits_dates_ordered", sql`${t.validTo} >= ${t.validFrom}`),
  ],
);

